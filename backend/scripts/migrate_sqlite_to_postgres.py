def _print_report(report: Report, *, dry_run: bool) -> None:
    print()
    print("=" * 72)
    print("DRY RUN - es wurde nichts geschrieben" if dry_run else "MIGRATIONSBERICHT")
    print("=" * 72)

    if report.source_counts:
        print()
        print(f"{'Tabelle':<28}{'SQLite':>10}{'PostgreSQL':>14}")
        print("-" * 52)
        for table in TABLE_ORDER:
            src = report.source_counts.get(table, 0)
            dst = report.target_counts.get(table, 0)
            print(f"{table:<28}{src:>10}{dst:>14}")

    if report.sequences:
        print()
        print("Sequenzen nach dem Import:")
        for table, value in report.sequences.items():
            print(f"  {table:<28} -> {value}")

    print()
    for check in report.checks:
        print(check.line())
    print()
    print("ERGEBNIS:", "PASS" if report.ok else "FAIL")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="migrate_sqlite_to_postgres",
        description=(
            "Überträgt eine Planner-SQLite-Datenbank nach PostgreSQL. Das Ziel wird "
            "ausschließlich über die Umgebungsvariable DATABASE_URL bestimmt."
        ),
    )
    parser.add_argument(
        "--source",
        type=Path,
        required=True,
        help="Pfad zur SQLite-Quelldatei (wird ausschließlich lesend geöffnet).",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Nur prüfen (Erreichbarkeit, Schema, Zeilenzahlen, Konflikte, Waisen).",
    )
    parser.add_argument(
        "--allow-non-empty",
        action="store_true",
        help=(
            "Erlaubt die Migration in eine bereits gefüllte Zieldatenbank. "
            "Vorhandene Daten werden dabei GELÖSCHT. Ohne diese Option bricht das "
            "Skript bei einem nicht leeren Ziel ab."
        ),
    )
    args = parser.parse_args(argv)

    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")

    if not os.getenv("DATABASE_URL"):
        print(
            "DATABASE_URL ist nicht gesetzt. Das Ziel wird bewusst nur über die "
            "Umgebung konfiguriert, damit keine Zugangsdaten in der Prozessliste "
            "oder der Shell-History landen.",
            file=sys.stderr,
        )
        return 2

    try:
        if args.dry_run:
            report = run_dry_run(args.source)
        else:
            report = run_migration(args.source, allow_non_empty=args.allow_non_empty)
    except MigrationAborted as exc:
        print(f"\nABBRUCH: {exc}", file=sys.stderr)
        return 1
    except (psycopg.Error, sqlite3.Error) as exc:
        print(f"\nDatenbankfehler: {exc}", file=sys.stderr)
        return 1

    _print_report(report, dry_run=args.dry_run)
    return 0 if report.ok else 1


if __name__ == "__main__":
    raise SystemExit(main())

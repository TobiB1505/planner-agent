#: Batchgröße für executemany. Groß genug, um nicht zeilenweise zu arbeiten,
#: klein genug, um bei sehr großen Tabellen den Speicher nicht zu sprengen.
BATCH_SIZE = 500


class MigrationAborted(RuntimeError):
    """Der Lauf wurde bewusst abgebrochen - nichts wurde geschrieben."""


@dataclass
class CheckResult:
    name: str
    passed: bool
    detail: str = ""

    def line(self) -> str:
        return f"[{'PASS' if self.passed else 'FAIL'}] {self.name}{f' - {self.detail}' if self.detail else ''}"


@dataclass
class Report:
    checks: list[CheckResult] = field(default_factory=list)
    source_counts: dict[str, int] = field(default_factory=dict)
    target_counts: dict[str, int] = field(default_factory=dict)
    sequences: dict[str, int] = field(default_factory=dict)

    def add(self, name: str, passed: bool, detail: str = "") -> CheckResult:
        result = CheckResult(name, passed, detail)
        self.checks.append(result)
        return result

    @property
    def ok(self) -> bool:
        return all(check.passed for check in self.checks)



def count_rows_pg(conn, table: str) -> int:
    statement = pgsql.SQL("SELECT COUNT(*) AS c FROM {}").format(pgsql.Identifier(table))
    return conn.execute(statement).fetchone()["c"]


def target_is_empty(conn) -> tuple[bool, dict[str, int]]:
    counts = {table: count_rows_pg(conn, table) for table in TABLE_ORDER}
    return (sum(counts.values()) == 0), counts


def check_target_schema(conn) -> None:
    version = current_version(conn)
    if version is None:
        raise MigrationAborted(
            "Die Zieldatenbank hat noch kein Schema. Bitte zuerst die Migrationen "
            "anwenden: python -c \"from backend import db; db.initialize_database()\""
        )
    logger.info("Zielschema vorhanden (Migrationsstand %s).", version)


def copy_table(source: sqlite3.Connection, target, table: str) -> int:
    """Überträgt eine Tabelle vollständig, inklusive IDs und NULL-Werten."""
    columns = TABLE_COLUMNS[table]
    available = set(source_columns(source, table))
    missing = [column for column in columns if column not in available]
    if missing:
        raise MigrationAborted(
            f"Tabelle {table}: Spalten fehlen in der SQLite-Quelle: {', '.join(missing)}. "
            "Quelle und Zielschema passen nicht zusammen - Abbruch ohne Schreiben."
        )

    select = pgsql.SQL("")  # nur zur Klarheit: die Quelle ist SQLite, kein psycopg-SQL
    del select
    column_list = ", ".join(columns)
    cursor = source.execute(f"SELECT {column_list} FROM {table} ORDER BY rowid")

    insert = pgsql.SQL("INSERT INTO {} ({}) VALUES ({})").format(
        pgsql.Identifier(table),
        pgsql.SQL(", ").join(pgsql.Identifier(column) for column in columns),
        pgsql.SQL(", ").join(pgsql.Placeholder() * len(columns)),
    )

    transferred = 0
    while True:
        batch = cursor.fetchmany(BATCH_SIZE)
        if not batch:
            break
        # tuple(row) erhält NULL-Werte als None und übernimmt die Typen
        # unverändert - INTEGER bleibt Ganzzahl, REAL bleibt Gleitkomma, TEXT
        # bleibt Text. Genau das will das Zielschema (siehe Migration 001).
        target.executemany(insert, [tuple(row) for row in batch])
        transferred += len(batch)
    return transferred


def fix_sequences(target) -> dict[str, int]:
    """Setzt jede IDENTITY-Sequenz auf MAX(id), damit der nächste Insert darüber liegt.

    Ohne diesen Schritt würde die Sequenz nach einem Import mit expliziten IDs
    weiter bei 1 stehen und der erste neue Datensatz sofort mit einem
    Primärschlüsselkonflikt scheitern.
    """
    results: dict[str, int] = {}
    for table in TABLES_WITH_IDENTITY:
        row = target.execute(
            pgsql.SQL(
                """SELECT setval(
                       pg_get_serial_sequence({table_literal}, 'id'),
                       COALESCE((SELECT MAX(id) FROM {table}), 1),
                       (SELECT MAX(id) IS NOT NULL FROM {table})
                   ) AS value"""
            ).format(
                table_literal=pgsql.Literal(table),
                table=pgsql.Identifier(table),
            )
        ).fetchone()
        results[table] = row["value"]
    return results


def find_orphans_pg(conn) -> list[tuple[str, str, str, int]]:
    orphans: list[tuple[str, str, str, int]] = []
    for child, column, parent, parent_column in FOREIGN_KEYS:
        statement = pgsql.SQL(
            """SELECT COUNT(*) AS c FROM {child} c
               WHERE c.{column} IS NOT NULL
                 AND NOT EXISTS (
                     SELECT 1 FROM {parent} p WHERE p.{parent_column} = c.{column}
                 )"""
        ).format(
            child=pgsql.Identifier(child),
            column=pgsql.Identifier(column),
            parent=pgsql.Identifier(parent),
            parent_column=pgsql.Identifier(parent_column),
        )
        count = conn.execute(statement).fetchone()["c"]
        if count:
            orphans.append((child, column, parent, count))
    return orphans



def open_source(path: Path) -> sqlite3.Connection:
    """Öffnet die SQLite-Quelle read-only.

    `mode=ro` verhindert jede Schreiboperation auf Ebene der SQLite-Engine -
    das Skript kann die Ausgangsdatei also nicht verändern, auch nicht durch
    einen Programmierfehler. `sqlite3.connect()` würde eine fehlende Datei
    sonst stillschweigend als leere Datenbank neu anlegen; die URI-Form mit
    mode=ro schlägt stattdessen sauber fehl.
    """
    if not path.exists():
        raise MigrationAborted(f"SQLite-Quelldatei nicht gefunden: {path}")
    conn = sqlite3.connect(f"file:{path}?mode=ro", uri=True)
    conn.row_factory = sqlite3.Row
    return conn


def source_tables(conn: sqlite3.Connection) -> set[str]:
    return {
        row["name"]
        for row in conn.execute(
            "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'"
        )
    }


def source_columns(conn: sqlite3.Connection, table: str) -> list[str]:
    return [row["name"] for row in conn.execute(f"PRAGMA table_info({table})")]


def count_rows_sqlite(conn: sqlite3.Connection, table: str) -> int:
    return conn.execute(f"SELECT COUNT(*) AS c FROM {table}").fetchone()["c"]


def find_orphans_sqlite(conn: sqlite3.Connection) -> list[tuple[str, str, str, int]]:
    """Findet Waisen in den Altdaten.

    Notwendig, weil SQLite die Fremdschlüssel nie erzwungen hat (PRAGMA
    foreign_keys wurde im Projekt nirgends gesetzt) - PostgreSQL tut es ab
    jetzt. Es wird nichts gelöscht und nichts repariert, nur berichtet.
    """
    orphans: list[tuple[str, str, str, int]] = []
    tables = source_tables(conn)
    for child, column, parent, parent_column in FOREIGN_KEYS:
        if child not in tables or parent not in tables:
            continue
        count = conn.execute(
            f"""SELECT COUNT(*) AS c FROM {child} c
                WHERE c.{column} IS NOT NULL
                  AND NOT EXISTS (
                      SELECT 1 FROM {parent} p WHERE p.{parent_column} = c.{column}
                  )"""
        ).fetchone()["c"]
        if count:
            orphans.append((child, column, parent, count))
    return orphans



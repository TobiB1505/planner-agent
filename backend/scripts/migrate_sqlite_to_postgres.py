def run_dry_run(source_path: Path) -> Report:
    """Prüft alles, schreibt nichts (Sprint-Punkt 23)."""
    report = Report()
    source = open_source(source_path)
    target = db_module.connect_direct()
    try:
        report.add("Quelle erreichbar", True, str(source_path))
        report.add("Ziel erreichbar", True, "über DATABASE_URL")

        version = current_version(target)
        report.add(
            "Zielschema vorhanden",
            version is not None,
            f"Migrationsstand {version}" if version else
            "keine Migration angewendet - zuerst db.initialize_database() ausführen",
        )

        tables = source_tables(source)
        missing = [table for table in TABLE_ORDER if table not in tables]
        report.add(
            "Alle erwarteten Tabellen in der Quelle",
            not missing,
            f"fehlen: {', '.join(missing)}" if missing else f"{len(TABLE_ORDER)}/{len(TABLE_ORDER)}",
        )

        for table in TABLE_ORDER:
            report.source_counts[table] = count_rows_sqlite(source, table) if table in tables else 0

        # Alles Weitere setzt ein vorhandenes Zielschema voraus. Ohne das
        # würde die erste fehlschlagende Abfrage die Transaktion abbrechen und
        # jede folgende Prüfung mit einem Folgefehler übertönen - der Bericht
        # bliebe dann bei "relation does not exist" statt die eigentliche
        # Ursache zu nennen.
        if version is None:
            return report

        for table in TABLE_ORDER:
            report.target_counts[table] = count_rows_pg(target, table)

        empty, counts = target_is_empty(target)
        report.add(
            "Ziel ist leer",
            empty,
            "leer" if empty else
            "belegt: " + ", ".join(f"{t}={c}" for t, c in counts.items() if c),
        )

        orphans = find_orphans_sqlite(source)
        report.add(
            "Keine Waisen in den Altdaten",
            not orphans,
            "; ".join(f"{c}.{col} -> {p}: {n}" for c, col, p, n in orphans) if orphans else
            f"{len(FOREIGN_KEYS)} Beziehungen geprüft",
        )
    finally:
        source.close()
        target.close()
    return report


def run_migration(source_path: Path, *, allow_non_empty: bool) -> Report:
    report = Report()
    source = open_source(source_path)
    target = db_module.connect_direct()
    try:
        check_target_schema(target)

        tables = source_tables(source)
        missing = [table for table in TABLE_ORDER if table not in tables]
        if missing:
            raise MigrationAborted(
                "In der SQLite-Quelle fehlen Tabellen: " + ", ".join(missing)
            )

        orphans = find_orphans_sqlite(source)
        if orphans:
            details = "\n".join(
                f"  - {child}.{column} verweist auf nicht vorhandene {parent}: {count} Zeilen"
                for child, column, parent, count in orphans
            )
            raise MigrationAborted(
                "Die Altdaten enthalten verwaiste Verweise. PostgreSQL erzwingt die "
                "Fremdschlüssel, die SQLite nie geprüft hat - die Migration würde "
                "scheitern.\n" + details + "\n"
                "Es wurde NICHTS gelöscht und NICHTS geschrieben. Bitte fachlich "
                "entscheiden, wie mit diesen Zeilen umgegangen wird."
            )

        empty, counts = target_is_empty(target)
        if not empty:
            if not allow_non_empty:
                belegt = ", ".join(f"{t}={c}" for t, c in counts.items() if c)
                raise MigrationAborted(
                    f"Die Zieldatenbank ist nicht leer ({belegt}). Abbruch, es wurde "
                    "nichts geschrieben. Wenn der vorhandene Inhalt bewusst ersetzt "
                    "werden soll: --allow-non-empty."
                )
            logger.warning(
                "--allow-non-empty: die folgenden vorhandenen Datensätze werden GELÖSCHT: %s",
                ", ".join(f"{t}={c}" for t, c in counts.items() if c),
            )

        for table in TABLE_ORDER:
            report.source_counts[table] = count_rows_sqlite(source, table)

        # Ab hier eine einzige Transaktion: entweder alles oder nichts.
        try:
            if not empty:
                db_module.truncate_all_tables(target)
            for table in TABLE_ORDER:
                transferred = copy_table(source, target, table)
                logger.info("%-26s %6d Zeilen", table, transferred)
            report.sequences = fix_sequences(target)
            target.commit()
        except Exception as exc:  # noqa: BLE001 - wird sofort neu geworfen
            target.rollback()
            raise MigrationAborted(
                f"Migration fehlgeschlagen und vollständig zurückgerollt: {exc}"
            ) from exc

        # --- Verifikation (Sprint-Punkte 24/25) ---
        for table in TABLE_ORDER:
            report.target_counts[table] = count_rows_pg(target, table)
            report.add(
                f"Zeilenzahl {table}",
                report.source_counts[table] == report.target_counts[table],
                f"SQLite {report.source_counts[table]} / PostgreSQL {report.target_counts[table]}",
            )

        business_samples(source, target, report)

        remaining = find_orphans_pg(target)
        report.add(
            "Referenzielle Integrität im Ziel",
            not remaining,
            "; ".join(f"{c}.{col} -> {p}: {n}" for c, col, p, n in remaining) if remaining else
            f"{len(FOREIGN_KEYS)} Beziehungen geprüft",
        )

        for table, value in report.sequences.items():
            max_row = target.execute(
                pgsql.SQL("SELECT COALESCE(MAX(id), 0) AS m FROM {}").format(
                    pgsql.Identifier(table)
                )
            ).fetchone()
            report.add(
                f"Sequenz {table}",
                value >= max_row["m"],
                f"setval={value}, MAX(id)={max_row['m']}",
            )
    finally:
        source.close()
        target.close()
    return report



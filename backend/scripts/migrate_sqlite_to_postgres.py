"""Überträgt eine bestehende Planner-SQLite-Datenbank nach PostgreSQL.

    python -m backend.scripts.migrate_sqlite_to_postgres --source local_data/database/dienstplaene.db --dry-run
    python -m backend.scripts.migrate_sqlite_to_postgres --source local_data/database/dienstplaene.db

Grundsätze (Sprint-Punkte 20-25):

  * Die SQLite-Quelle wird ausschließlich LESEND geöffnet (`mode=ro`, immutable
    URI). Das Skript kann die Ausgangsdaten nicht beschädigen.
  * Das Ziel kommt ausschließlich aus DATABASE_URL - nie aus einem Argument,
    damit keine Zugangsdaten in der Prozessliste oder Shell-History landen.
  * Standardmäßig sicher: ist das Ziel nicht leer, bricht das Skript ab. Erst
    `--allow-non-empty` erlaubt das Überschreiben, und auch dann wird jeder
    gelöschte Datensatz vorher gezählt und gemeldet.
  * Alles läuft in EINER Transaktion. Ein Fehler an irgendeiner Stelle rollt
    den gesamten Lauf zurück - es gibt keinen halb migrierten Zustand.
  * IDs werden explizit übernommen (die IDENTITY-Spalten sind bewusst
    GENERATED BY DEFAULT). Danach werden die Sequenzen auf MAX(id) gesetzt, so
    dass der nächste Insert garantiert darüber liegt.
  * Nach dem Schreiben wird verifiziert: Zeilenzahlen pro Tabelle, fachliche
    Stichproben und referenzielle Integrität - jeweils mit PASS/FAIL.
  * Waisen in den Altdaten werden NIE automatisch gelöscht. Sie werden gemeldet
    und führen zum Abbruch, weil PostgreSQL die Fremdschlüssel jetzt erzwingt.
"""

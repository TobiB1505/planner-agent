def business_samples(source: sqlite3.Connection, target, report: Report) -> None:
    """Vergleicht nicht nur Zeilenzahlen, sondern konkrete fachliche Ergebnisse.

    Eine reine COUNT-Prüfung würde eine vertauschte Spaltenzuordnung nicht
    bemerken. Deshalb hier gezielt die Zusammenhänge, an denen der Planner
    tatsächlich hängt: Aliasse einer Person, Zuweisungen einer Woche, Personen
    einer Probe, Abwesenheitseinträge.
    """
    tables = source_tables(source)

    # 1. Aliasse pro Person (Personenauflösung)
    if {"people", "people_aliases"} <= tables:
        row = source.execute(
            """SELECT p.id, p.name FROM people p
               JOIN people_aliases a ON a.person_id = p.id
               GROUP BY p.id ORDER BY COUNT(*) DESC, p.id LIMIT 1"""
        ).fetchone()
        if row is None:
            report.add("Stichprobe Aliase", True, "keine Aliase vorhanden")
        else:
            src = {
                r["alias"]
                for r in source.execute(
                    "SELECT alias FROM people_aliases WHERE person_id = ?", (row["id"],)
                )
            }
            dst = {
                r["alias"]
                for r in target.execute(
                    "SELECT alias FROM people_aliases WHERE person_id = %s", (row["id"],)
                ).fetchall()
            }
            report.add(
                f"Stichprobe Aliase (Mitarbeiter {row['name']!r})",
                src == dst,
                f"SQLite {len(src)} / PostgreSQL {len(dst)}",
            )

    # 2. Zuweisungen einer konkreten Kalenderwoche
    if {"week_plans", "assignments"} <= tables:
        row = source.execute(
            """SELECT w.id, w.start_date FROM week_plans w
               JOIN assignments a ON a.week_plan_id = w.id
               GROUP BY w.id ORDER BY COUNT(*) DESC, w.id LIMIT 1"""
        ).fetchone()
        if row is None:
            report.add("Stichprobe Zuweisungen", True, "keine Zuweisungen vorhanden")
        else:
            src = sorted(
                (r["date"], r["category"], r["subcategory"], r["person_id"])
                for r in source.execute(
                    """SELECT date, category, subcategory, person_id
                       FROM assignments WHERE week_plan_id = ?""",
                    (row["id"],),
                )
            )
            dst = sorted(
                (r["date"], r["category"], r["subcategory"], r["person_id"])
                for r in target.execute(
                    """SELECT date, category, subcategory, person_id
                       FROM assignments WHERE week_plan_id = %s""",
                    (row["id"],),
                ).fetchall()
            )
            report.add(
                f"Stichprobe Zuweisungen (KW ab {row['start_date']})",
                src == dst,
                f"{len(src)} Zeilen",
            )

    # 3. Personen einer Probe
    if {"rehearsals", "rehearsal_people"} <= tables:
        row = source.execute(
            """SELECT r.id, r.activity FROM rehearsals r
               JOIN rehearsal_people rp ON rp.rehearsal_id = r.id
               GROUP BY r.id ORDER BY COUNT(*) DESC, r.id LIMIT 1"""
        ).fetchone()
        if row is None:
            report.add("Stichprobe Probenteilnehmer", True, "keine Proben vorhanden")
        else:
            src = sorted(
                (r["raw_name"], r["person_name"], r["role"])
                for r in source.execute(
                    "SELECT raw_name, person_name, role FROM rehearsal_people WHERE rehearsal_id = ?",
                    (row["id"],),
                )
            )
            dst = sorted(
                (r["raw_name"], r["person_name"], r["role"])
                for r in target.execute(
                    "SELECT raw_name, person_name, role FROM rehearsal_people WHERE rehearsal_id = %s",
                    (row["id"],),
                ).fetchall()
            )
            report.add(
                f"Stichprobe Probenteilnehmer ({row['activity']!r})",
                src == dst,
                f"{len(src)} Personen",
            )

    # 4. Abwesenheiten (Urlaub/Frei/krank)
    if "absences" in tables:
        src = sorted(
            (r["date"], r["person_id"], r["typ"])
            for r in source.execute("SELECT date, person_id, typ FROM absences")
        )
        dst = sorted(
            (r["date"], r["person_id"], r["typ"])
            for r in target.execute("SELECT date, person_id, typ FROM absences").fetchall()
        )
        report.add("Stichprobe Abwesenheiten", src == dst, f"{len(src)} Einträge")

    # 5. Manuelle Gedächtnis-Korrekturen (dürfen unter keinen Umständen verloren gehen)
    if "person_memory_overrides" in tables:
        src = sorted(
            (r["person_id"], r["facet"], r["item_key"], r["state"])
            for r in source.execute(
                "SELECT person_id, facet, item_key, state FROM person_memory_overrides"
            )
        )
        dst = sorted(
            (r["person_id"], r["facet"], r["item_key"], r["state"])
            for r in target.execute(
                "SELECT person_id, facet, item_key, state FROM person_memory_overrides"
            ).fetchall()
        )
        report.add("Stichprobe Gedächtnis-Overrides", src == dst, f"{len(src)} Einträge")


